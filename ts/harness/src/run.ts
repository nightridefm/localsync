// Runs the capability catalogue and prints the result; `--write` also
// writes docs/capability-matrix.md.
//
//   pnpm harness matrix [--only=1,6] [--write]
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseArgs } from 'node:util'

import { introspect } from './catalog.ts'
import { catalogue } from './catalogue/index.ts'
import { buildEngine, LocalsyncAdapter } from './localsync.ts'
import { ensureFixture, resetData } from './fixture.ts'
import { Db } from './pg.ts'
import { Ctx, Fail, type Result } from './scenario.ts'

const { values } = parseArgs({
	options: {
		only: { type: 'string' },
		write: { type: 'boolean', default: false },
		timeout: { type: 'string', default: '300000' },
	},
})

const only = values.only ? new Set(values.only.split(',')) : null
const scenarios = catalogue.filter((s) => !only || only.has(s.id))
const timeoutMs = Number(values.timeout)

const db = new Db()

buildEngine()
const adapter = new LocalsyncAdapter()
await ensureFixture(db)
const results = new Map<string, Result>()
for (const s of scenarios) {
	await resetData(db)
	const ctx = new Ctx(db, adapter, await introspect(db))
	const start = Date.now()
	let r: Result
	try {
		let timer: NodeJS.Timeout | undefined
		const note = await Promise.race([
			s.run(ctx),
			new Promise<never>((_, reject) => {
				timer = setTimeout(() => reject(new Fail(`timed out after ${timeoutMs}ms`)), timeoutMs)
			}),
		]).finally(() => clearTimeout(timer))
		r = { status: 'pass', note: note ?? '', ms: Date.now() - start }
	} catch (err) {
		const status = err instanceof Fail ? 'fail' : 'error'
		r = { status, note: err instanceof Error ? err.message : String(err), ms: Date.now() - start }
	} finally {
		await ctx.closeAll()
	}
	results.set(s.id, r)
	console.log(`${s.id.padEnd(4)} ${r.status.padEnd(11)} ${s.title}`)
	if (r.note) console.log(`${' '.repeat(5)}${r.note.split('\n').join(`\n${' '.repeat(5)}`)}`)
}
await adapter.close()
await db.close()

if (values.write) {
	const cell = (r: Result | undefined) => {
		if (!r) return '-'
		const lines = r.note
			.split('\n')
			.map((l) => l.trim())
			.filter(Boolean)
		let note = lines.slice(0, 2).join(' ')
		if (note.length > 220) note = `${note.slice(0, 220)}...`
		return `${r.status}${note ? `: ${note.replaceAll('|', '\\|')}` : ''}`
	}
	const lines = [
		'# Capability matrix',
		'',
		`Generated by \`ts/harness/src/run.ts\` on ${new Date().toISOString().slice(0, 10)}. Each row is`,
		"the observable outcome on the reference client (localdb's real code on",
		'in-memory sqlite-wasm) compared with the oracle (the rule SQL run in',
		'Postgres). The same catalogue against Electric 1.7.9 is in',
		'[`electric-comparison.md`](electric-comparison.md).',
		'',
		'| # | Capability | localsync |',
		'| --- | --- | --- |',
		...scenarios.map((s) => `| ${s.id} | ${s.title} | ${cell(results.get(s.id))} |`),
		'',
		'13 uses the read-your-writes convention (docs/design.md section 12): the',
		'write also upserts a `client_mutation` row the client syncs.',
		'',
	]
	writeFileSync(
		path.resolve(import.meta.dirname, '../../../docs/capability-matrix.md'),
		lines.join('\n')
	)
}

// Any scenario that did not pass fails the run (CI relies on it).
process.exit([...results.values()].every((r) => r.status === 'pass') ? 0 : 1)
