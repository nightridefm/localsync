// Runs the capability catalogue against one or more adapters and prints the
// matrix; `--write` also writes docs/capability-matrix.md.
//
//   pnpm --filter @nightride/localsync-harness matrix [--only=1,6] [--write]
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseArgs } from 'node:util'

import { type Adapter, Unsupported } from './adapter.ts'
import { introspect } from './catalog.ts'
import { catalogue } from './catalogue/index.ts'
import { ElectricAdapter } from './electric.ts'
import { buildEngine, LocalsyncAdapter } from './localsync.ts'
import { ensureFixture, resetData } from './fixture.ts'
import { Db } from './pg.ts'
import { Ctx, Fail, type Result } from './scenario.ts'

const { values } = parseArgs({
	options: {
		only: { type: 'string' },
		adapter: { type: 'string', default: 'electric' },
		write: { type: 'boolean', default: false },
		timeout: { type: 'string', default: '300000' },
	},
})

const adapters: Record<string, () => Adapter> = {
	electric: () => new ElectricAdapter(),
	localsync: () => {
		buildEngine()
		return new LocalsyncAdapter()
	},
}

const only = values.only ? new Set(values.only.split(',')) : null
const scenarios = catalogue.filter((s) => !only || only.has(s.id))
const timeoutMs = Number(values.timeout)

const db = new Db()
const results = new Map<string, Map<string, Result>>()

for (const name of values.adapter!.split(',')) {
	const make = adapters[name]
	if (!make) throw new Error(`unknown adapter ${name}`)
	const adapter = make()
	if ((await ensureFixture(db)) && adapter.schemaReset) await adapter.schemaReset(db)
	const col = new Map<string, Result>()
	results.set(adapter.name, col)
	for (const s of scenarios) {
		await resetData(db)
		const ctx = new Ctx(db, adapter, await introspect(db))
		const start = Date.now()
		let r: Result
		try {
			let timer: NodeJS.Timeout | undefined
			const note = await Promise.race([
				s.run(ctx),
				new Promise<never>((_, reject) => {
					timer = setTimeout(() => reject(new Fail(`timed out after ${timeoutMs}ms`)), timeoutMs)
				}),
			]).finally(() => clearTimeout(timer))
			r = { status: 'pass', note: note ?? '', ms: Date.now() - start }
		} catch (err) {
			const status =
				err instanceof Unsupported ? 'unsupported' : err instanceof Fail ? 'fail' : 'error'
			r = { status, note: err instanceof Error ? err.message : String(err), ms: Date.now() - start }
		} finally {
			await ctx.closeAll()
		}
		col.set(s.id, r)
		console.log(`${adapter.name.padEnd(16)} ${s.id.padEnd(4)} ${r.status.padEnd(11)} ${s.title}`)
		if (r.status !== 'pass' && r.note)
			console.log(`${' '.repeat(22)}${r.note.split('\n').join(`\n${' '.repeat(22)}`)}`)
	}
	await adapter.close()
}
await db.close()

if (values.write) {
	const names = [...results.keys()]
	const cell = (r: Result | undefined) => {
		if (!r) return '-'
		const lines = r.note
			.split('\n')
			.map((l) => l.trim())
			.filter(Boolean)
		let note = lines.slice(0, 2).join(' ')
		if (note.length > 220) note = `${note.slice(0, 220)}...`
		return `${r.status}${note ? `: ${note.replaceAll('|', '\\|')}` : ''}`
	}
	const lines = [
		'# Capability matrix',
		'',
		`Generated by \`ts/harness/src/run.ts\` on ${new Date().toISOString().slice(0, 10)}. Each cell is`,
		"the observable outcome on the reference client (localdb's own sync code on",
		'in-memory sqlite-wasm) compared with the oracle (the rule SQL run in Postgres).',
		'',
		`| # | Capability | ${names.join(' | ')} |`,
		`| --- | --- | ${names.map(() => '---').join(' | ')} |`,
		...scenarios.map(
			(s) =>
				`| ${s.id} | ${s.title} | ${names.map((n) => cell(results.get(n)!.get(s.id))).join(' | ')} |`
		),
		'',
		'## Notes',
		'',
		"- The Electric column runs localdb's own Electric client code, so some",
		'  failures are client-side: catalogue 1 (`pgArrayToJson` turns the',
		"  `text[]` element `'1'` into the number 1) and 12b (a column added",
		'  upstream wedges the shape: `table ... has no column named extra`). They',
		'  are bugs to fix in localdb, not Electric limitations.',
		'- 6, 13, 14 and 15 are structural for Electric: one stream per shape, so a',
		'  transaction spanning shapes (or a 100k-row one split across responses,',
		'  or a subscription swap) is applied as several local commits.',
		'- 10a: Electric has no client authentication; the app proxy authorises',
		'  each shape request. 16: localdb holds one Electric shape per table.',
		'- 13 uses the read-your-writes convention of docs/design.md Q10: the',
		'  write also upserts a `client_mutation` row the client syncs.',
		'',
	]
	writeFileSync(
		path.resolve(import.meta.dirname, '../../../docs/capability-matrix.md'),
		lines.join('\n')
	)
}
