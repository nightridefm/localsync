// Fan-out benchmark: many connections asking for the same, already warm
// unit (a user's tabs and devices, a reconnect storm after a network blip).
// localsync answers them from its snapshot cache; Electric from its shape
// log. Reports the time until every client equals the oracle, bytes per
// client and, for localsync, how many snapshot queries Postgres ran.
//
//   pnpm --filter @nightride/localsync-harness bench:fanout [--clients=20] [--rows=10000] [--write]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseArgs } from 'node:util'

import type { Adapter } from './adapter.ts'
import { introspect } from './catalog.ts'
import { ElectricAdapter } from './electric.ts'
import { ensureFixture, resetData, seedWorld } from './fixture.ts'
import { buildEngine, LocalsyncAdapter } from './localsync.ts'
import { Db } from './pg.ts'
import { Ctx } from './scenario.ts'

const { values } = parseArgs({
	options: {
		adapter: { type: 'string', default: 'localsync,electric' },
		clients: { type: 'string', default: '20' },
		rows: { type: 'string', default: '10000' },
		write: { type: 'boolean', default: false },
	},
})
const clients = Number(values.clients)
const rows = Number(values.rows)
const PORT = Number(process.env.LOCALSYNC_ENGINE_PORT ?? 3141)

type Result = {
	name: string
	firstMs: number
	fanoutMs: number
	staggeredP50: number
	bytesPerClient: number
	snapshotQueries?: number
	cacheHits?: number
	rssMB?: number
}

function rssMB(pid: number | undefined): number | undefined {
	if (!pid) return undefined
	const m = /VmRSS:\s+(\d+) kB/.exec(readFileSync(`/proc/${pid}/status`, 'utf8'))
	return m ? Math.round(Number(m[1]) / 1024) : undefined
}

async function bench(adapter: Adapter, db: Db): Promise<Result> {
	await resetData(db)
	const ctx = new Ctx(db, adapter, await introspect(db))
	const p = ctx.principal()
	await ctx.write(async (q) => {
		await seedWorld(q, { orgs: 1, projects: 1, tasks: rows, comments: 1, memberOf: [[p.sub]] })
	})
	let t0 = Date.now()
	const first = await ctx.connect(p, ['tasks', 'comments'])
	await ctx.converge(first, 300_000)
	const firstMs = Date.now() - t0

	t0 = Date.now()
	const conns = await Promise.all(
		Array.from({ length: clients }, () => ctx.connect(p, ['tasks', 'comments']))
	)
	await Promise.all(conns.map((c) => ctx.converge(c, 300_000)))
	const fanoutMs = Date.now() - t0
	let bytes = 0
	for (const c of conns) bytes += c.client.bytes()

	// Staggered: connections arrive one after another (tabs opened over a
	// minute, devices waking), each after the previous one converged, so no
	// in-flight query can be shared.
	const staggered: number[] = []
	for (let i = 0; i < clients; i++) {
		const t = Date.now()
		const c = await ctx.connect(p, ['tasks', 'comments'])
		await ctx.converge(c, 300_000)
		staggered.push(Date.now() - t)
		await c.client.close()
	}
	staggered.sort((a, b) => a - b)

	const r: Result = {
		name: adapter.name,
		firstMs,
		fanoutMs,
		staggeredP50: staggered[Math.floor(staggered.length / 2)]!,
		bytesPerClient: Math.round(bytes / clients),
	}
	if (adapter instanceof LocalsyncAdapter) {
		const s = (await (await fetch(`http://127.0.0.1:${PORT}/debug/units`)).json()) as {
			snapshotQueries: number
			cacheHits: number
		}
		r.snapshotQueries = s.snapshotQueries
		r.cacheHits = s.cacheHits
		r.rssMB = rssMB(adapter.enginePid())
	}
	await ctx.closeAll()
	return r
}

const db = new Db()
const results: Result[] = []
for (const name of values.adapter!.split(',')) {
	let adapter: Adapter
	if (name === 'electric') adapter = new ElectricAdapter()
	else {
		buildEngine()
		adapter = new LocalsyncAdapter()
	}
	if ((await ensureFixture(db)) && adapter.schemaReset) await adapter.schemaReset(db)
	const r = await bench(adapter, db)
	await adapter.close()
	results.push(r)
	console.log(JSON.stringify(r))
}
await db.close()

if (values.write) {
	const lines = [
		`# Fan-out benchmark (${new Date().toISOString().slice(0, 10)})`,
		'',
		'Generated by `ts/harness/src/bench-fanout.ts`. One principal syncs `tasks`',
		`and \`comments\` (${rows} tasks, one comment each); after the first client`,
		`has converged, ${clients} more connections ask for the same two units at`,
		'once (a reconnect storm), then another',
		`${clients} arrive one at a time (tabs and devices opened over time),`,
		'each after the previous one converged. Times are until a client equals',
		'the oracle. All clients share one Node event loop, so the burst time is',
		'dominated by client-side apply, not the server.',
		'',
		'| Engine | First client | Burst (all converged) | Staggered p50 | Bytes / client | Snapshot queries | Cache hits | Engine RSS |',
		'| --- | --- | --- | --- | --- | --- | --- | --- |',
		...results.map(
			(r) =>
				`| ${r.name} | ${r.firstMs} ms | ${r.fanoutMs} ms | ${r.staggeredP50} ms | ${r.bytesPerClient.toLocaleString('en')} | ${r.snapshotQueries ?? '-'} | ${r.cacheHits ?? '-'} | ${r.rssMB ? `${r.rssMB} MB` : '-'} |`
		),
		'',
		'Snapshot queries count queries run to give a client a unit; the first',
		"client's two units are created by queries that are not counted (unit",
		'creation), and their results seed the cache. Without the cache',
		'(`LOCALSYNC_SNAP_CACHE=0`) the burst still needs only one query per unit,',
		'because waiting clients share an in-flight query; the staggered clients',
		'need one per unit each.',
		'',
	]
	const dir = path.resolve(import.meta.dirname, '../../../docs/bench')
	mkdirSync(dir, { recursive: true })
	writeFileSync(path.join(dir, 'fanout.md'), lines.join('\n'))
}
